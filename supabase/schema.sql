-- ============================================================
--  PORTALE CALL CENTER — Depuratoritalia
--  Schema Supabase. Tutte le tabelle hanno prefisso cc_ così
--  convivono senza conflitti con quelle del Portale Tecnici.
--  Da eseguire una volta nel SQL Editor del progetto Supabase.
-- ============================================================

-- Operatrici e admin (login = nome + PIN, come nel Portale Tecnici)
create table if not exists cc_operatrici (
  id              bigint generated by default as identity primary key,
  nome            text        not null,
  pin             text        not null,
  ruolo           text        not null default 'operatrice' check (ruolo in ('admin','operatrice')),
  attiva          boolean     not null default true,
  tipi_nascosti   text[]      not null default '{}',     -- codici di cc_tipi che questa operatrice NON vede
  squadra         text,                                  -- es. 'Mattino' / 'Pomeriggio': l'admin può vederle separate
  ultimo_accesso  timestamptz,
  created_at      timestamptz not null default now()
);

-- Tipi di attività registrabili (configurabili dall'admin in Gestione)
create table if not exists cc_tipi (
  id               bigint generated by default as identity primary key,
  codice           text        not null unique,
  nome             text        not null,
  descrizione      text,
  icona            text        not null default 'ti-phone',
  colore           text        not null default 'blue',   -- blue | green | amber | red | pink | purple | indigo | gray
  ordine           int         not null default 0,
  attivo           boolean     not null default true,
  gruppo           text,                                  -- 'contatti' | 'appuntamenti' | null (per totali e resa)
  fonte            text,                                  -- es. 'CC', 'Stand': le attività con la stessa fonte stanno nella stessa scheda
  chiede_dettaglio boolean     not null default false,    -- true = apre la scheda cliente/data/note
  obiettivo_giorno int         not null default 0,        -- 0 = nessun obiettivo
  created_at       timestamptz not null default now()
);

-- Una riga per ogni cosa registrata (un tap = una riga: così l'admin la vede subito)
create table if not exists cc_registrazioni (
  id                bigint generated by default as identity primary key,
  operatrice_id     bigint      references cc_operatrici(id) on delete cascade,   -- null = senza telefonista (demo dirette): conta sulla fonte
  tipo_codice       text        not null references cc_tipi(codice) on update cascade,
  data              date        not null default current_date,
  ora               timestamptz not null default now(),
  cliente           text,
  telefono          text,
  data_appuntamento date,
  note              text,
  demo              text check (demo in ('fatta','non_fatta')),  -- segnata dall'admin sugli appuntamenti
  demo_data         date,
  created_at        timestamptz not null default now()
);
create index if not exists cc_registrazioni_data_idx on cc_registrazioni(data);
create index if not exists cc_registrazioni_op_data_idx on cc_registrazioni(operatrice_id, data);

-- Turni: inizio / fine lavoro (serve all'admin per vedere chi è in linea adesso)
create table if not exists cc_turni (
  id            bigint generated by default as identity primary key,
  operatrice_id bigint      not null references cc_operatrici(id) on delete cascade,
  data          date        not null default current_date,
  inizio        timestamptz not null default now(),
  fine          timestamptz,
  created_at    timestamptz not null default now()
);
create index if not exists cc_turni_op_data_idx on cc_turni(operatrice_id, data);

-- Avvisi dell'admin alle operatrici
create table if not exists cc_avvisi (
  id         bigint generated by default as identity primary key,
  testo      text        not null,
  attivo     boolean     not null default true,
  created_at timestamptz not null default now()
);

-- Tempo reale: l'admin riceve le nuove registrazioni e i turni senza ricaricare
do $$
begin
  if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and tablename='cc_registrazioni') then
    alter publication supabase_realtime add table cc_registrazioni;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and tablename='cc_turni') then
    alter publication supabase_realtime add table cc_turni;
  end if;
end $$;

-- Accesso con la chiave anon come nel Portale Tecnici (nessun Supabase Auth).
alter table cc_operatrici   enable row level security;
alter table cc_tipi         enable row level security;
alter table cc_registrazioni enable row level security;
alter table cc_turni        enable row level security;
alter table cc_avvisi       enable row level security;
drop policy if exists cc_all on cc_operatrici;    create policy cc_all on cc_operatrici    for all using (true) with check (true);
drop policy if exists cc_all on cc_tipi;          create policy cc_all on cc_tipi          for all using (true) with check (true);
drop policy if exists cc_all on cc_registrazioni; create policy cc_all on cc_registrazioni for all using (true) with check (true);
drop policy if exists cc_all on cc_turni;         create policy cc_all on cc_turni         for all using (true) with check (true);
drop policy if exists cc_all on cc_avvisi;        create policy cc_all on cc_avvisi        for all using (true) with check (true);

